// Builds ideas.js from the markdown files in ./ideas
//
//   ideas/<status>/<idea name>.md
//
//   status folder : exploring | prototype | ready-to-demo   (also accepts "ready")
//   file name     : becomes the card title  (sandbox-factory.md -> "Sandbox Factory")
//
// Inside each file:
//   first paragraph      -> the one-line pitch shown on the card
//   ## Problem           -> optional
//   ## Approach          -> optional
//   ## Next              -> optional
//   Tags: a, b, c        -> optional
//   Demo: https://...    -> optional (or Demo: [Label](https://...))
//
// Run after adding or editing ideas:   node build-ideas.mjs
// Then commit ideas.js together with the markdown files.

import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join, dirname, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const ideasDir = join(root, "ideas");
const STATUS = { exploring: "exploring", prototype: "prototype", ready: "ready", "ready-to-demo": "ready" };
const ORDER = { ready: 0, prototype: 1, exploring: 2 };

const titleFrom = (file) => {
  const name = basename(file, extname(file)).replace(/[-_]+/g, " ").trim();
  return /[A-Z]/.test(name) ? name : name.replace(/\b\w/g, (c) => c.toUpperCase());
};
const squash = (lines) => lines.join(" ").replace(/\s+/g, " ").trim();

function parse(md) {
  const sections = { pitch: [], problem: [], approach: [], next: [] };
  let cur = "pitch";
  let pitchDone = false;
  let tags = [];
  let url = "";
  let urlLabel = "";

  for (const raw of md.replace(/\r/g, "").split("\n")) {
    const line = raw.trim();
    const heading = /^#{1,6}\s+(.*)$/.exec(line);
    if (heading) {
      const h = heading[1].trim().toLowerCase();
      cur = h in sections ? h : null; // unknown headings (and the H1) are ignored
      continue;
    }
    const tagLine = /^tags?\s*:\s*(.+)$/i.exec(line);
    if (tagLine) { tags = tagLine[1].split(",").map((s) => s.trim()).filter(Boolean); continue; }
    const demo = /^demo\s*:\s*(.+)$/i.exec(line);
    if (demo) {
      const link = /^\[(.+?)\]\((https?:\/\/[^\s)]+)\)$/.exec(demo[1].trim());
      if (link) { urlLabel = link[1]; url = link[2]; }
      else if (/^https?:\/\//i.test(demo[1].trim())) url = demo[1].trim();
      continue;
    }
    if (!cur) continue;
    if (cur === "pitch") {
      if (line === "") { if (sections.pitch.length) pitchDone = true; continue; }
      if (!pitchDone) sections.pitch.push(line);
      continue;
    }
    if (line) sections[cur].push(line);
  }

  return {
    pitch: squash(sections.pitch),
    problem: squash(sections.problem),
    approach: squash(sections.approach),
    next: squash(sections.next),
    tags,
    url,
    urlLabel,
  };
}

const ideas = [];
if (existsSync(ideasDir)) {
  for (const folder of readdirSync(ideasDir)) {
    const full = join(ideasDir, folder);
    if (!statSync(full).isDirectory()) continue;
    const status = STATUS[folder.toLowerCase()];
    if (!status) { console.warn(`Skipping folder "${folder}": use exploring, prototype or ready-to-demo.`); continue; }
    for (const file of readdirSync(full).sort()) {
      if (extname(file).toLowerCase() !== ".md") continue;
      const data = parse(readFileSync(join(full, file), "utf8"));
      const idea = { title: titleFrom(file), status, ...data };
      if (!idea.pitch) console.warn(`${folder}/${file}: no pitch (first paragraph) found.`);
      for (const k of ["problem", "approach", "next", "url", "urlLabel"]) if (!idea[k]) delete idea[k];
      if (!idea.tags.length) delete idea.tags;
      ideas.push(idea);
    }
  }
}
ideas.sort((a, b) => ORDER[a.status] - ORDER[b.status] || a.title.localeCompare(b.title));

writeFileSync(
  join(root, "ideas.js"),
  "// Generated by build-ideas.mjs. Do not edit; change the files in ./ideas and re-run.\n" +
    "window.IDEAS = " + JSON.stringify(ideas, null, 2) + ";\n"
);
console.log(`ideas.js written with ${ideas.length} idea${ideas.length === 1 ? "" : "s"}.`);
